import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const folder = path.join(root, "9round-booking");
for (const [source, target] of [["index.html", "Member.html"], ["staff/index.html", "Staff.html"]]) {
  const file = path.join(folder, source);
  let html = fs.readFileSync(file, "utf8");
  html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, relative) =>
    "<style>\n" + fs.readFileSync(path.resolve(path.dirname(file), relative), "utf8") + "\n</style>");
  const scripts = [];
  html = html.replace(/<script src="([^"]+)" defer><\/script>/g, (_, relative) => {
    const resolved = path.resolve(path.dirname(file), relative);
    const content = path.basename(resolved) === "config.js"
      ? "window.ANAUTS_ROUND9_BOOKING = <?!= configJson ?>;"
      : fs.readFileSync(resolved, "utf8");
    scripts.push("<script>\n" + content.replace(/<\/script/gi, "<\\/script") + "\n</script>");
    return "";
  });
  // Inline scripts must run after the form elements have been rendered.
  html = html.replace("</body>", scripts.join("\n") + "\n</body>");
  html = html.replace(/[ \t]+$/gm, "");
  fs.writeFileSync(path.join(folder, "gas", target), "<!-- Generated by scripts/build-9round-gas-pages.mjs -->\n" + html);
}
